//! Общие помощники API: экранирование CSV.
//!
//! Выгрузка истории и наблюдаемость отдают CSV в одной и той же кодировке,
//! поэтому экранирование живёт здесь, а не дублируется в двух модулях.
//! Формат аудита (`audit.rs`) другой — там разделитель-запятая по RFC 4180
//! и без защиты от CSV-инъекции, поэтому он намеренно остаётся отдельным.

/// Экранирует значение для CSV: кавычки вокруг строк с `;`/кавычками/переводом
/// строки и апостроф перед ведущими `=`/`+`/`-`/`@`/TAB/CR (защита от
/// исполнения как формула в Excel).
#[must_use]
pub fn csv_escape(value: &str) -> String {
    let value =
        if value.starts_with(['=', '+', '-', '@', '\t', '\r']) { format!("'{value}") } else { value.to_string() };
    if value.contains([';', '"', '\n', '\r']) {
        format!("\"{}\"", value.replace('"', "\"\""))
    } else {
        value
    }
}
